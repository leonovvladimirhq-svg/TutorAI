async def check_substantive(question: str, answer: str) -> tuple[bool, str]:
    """Содержательный ли ответ. Возвращает (substantive, probe).

    При сбое модели считаем ответ содержательным — сценарий не должен зависать.
    Очень короткие ответы (< 15 символов) отсекаем без обращения к модели.
    """
    text = (answer or "").strip()
    if len(text) < 15:
        return False, "Расскажите чуть подробнее — что именно происходило и почему?"
    messages = [
        {"role": "system", "content": _SUBSTANTIVE_SYSTEM},
        {"role": "user", "content": f"Вопрос: {question}\nОтвет студента: {text}"},
    ]
    try:
        parsed = await llm.chat_json(messages, max_tokens=400)
    except Exception:  # noqa: BLE001
        logger.exception("Ошибка проверки содержательности ответа")
        return True, ""
    if not isinstance(parsed, dict):
        return True, ""
    substantive = bool(parsed.get("substantive", True))
    probe = str(parsed.get("probe", "")).strip()[:500]
    if not substantive and not probe:
        probe = "Расскажите чуть подробнее — что именно происходило и почему?"
    return substantive, probe


def _render_reflection_for_llm(goals_block: list[dict]) -> str:
    lines = []
    for g in goals_block:
        lines.append(f"Цель: {g['title']} — итог: {OUTCOME_LABELS.get(g['outcome'], g['outcome'])}")
        for key, label in QUESTION_LABELS.items():
            val = (g.get("answers") or {}).get(key)
            if val:
                lines.append(f"  {label}: {val}")
        if g.get("relevance_note"):
            lines.append(f"  Почему потеряла актуальность: {g['relevance_note']}")
    return "\n".join(lines)


async def summarize_patterns(goals_block: list[dict], student_patterns: str) -> str:
    """Сводка ИИ по закономерностям — ПОСЛЕ того, как студент сформулировал свои.

    goals_block: [{title, outcome, answers, relevance_note}]. Пустая строка при сбое.
    """
    messages = [
        {"role": "system", "content": _PATTERNS_SYSTEM},
        {"role": "user", "content": (
            f"Наблюдения студента о закономерностях:\n{student_patterns.strip() or '(не сформулировал)'}\n\n"
            f"Рефлексия по целям:\n{_render_reflection_for_llm(goals_block)}"
        )},
    ]
    try:
        parsed = await llm.chat_json(messages, max_tokens=900)
    except Exception:  # noqa: BLE001
        logger.exception("Ошибка сводки закономерностей")
        return ""
    if not isinstance(parsed, dict):
        return ""
    return str(parsed.get("summary", "")).strip()[:2000]
